// SPDX-License-Identifier: MIT
// LIC-2: every first-party source file carries the one-line
// `SPDX-License-Identifier: MIT` tag in its language's comment style (after a
// shebang or an HTML doctype), and no third-party, generated or fixture file
// carries it. The scope is found by rule, not from a frozen file list.
import test from "node:test";
import assert from "node:assert/strict";
import {
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { extname, join, resolve } from "node:path";

const repo = resolve(import.meta.dirname, "..");
const TAG = "SPDX-License-Identifier: MIT";
const LINE = {
  ".ts": `// ${TAG}`,
  ".tsx": `// ${TAG}`,
  ".mts": `// ${TAG}`,
  ".js": `// ${TAG}`,
  ".mjs": `// ${TAG}`,
  ".cjs": `// ${TAG}`,
  ".go": `// ${TAG}`,
  ".rs": `// ${TAG}`,
  ".css": `/* ${TAG} */`,
  ".html": `<!-- ${TAG} -->`,
  ".sh": `# ${TAG}`,
};
/** Directories whose first-party source files must carry the tag. */
const ROOTS = ["src", "web/src", "scripts", "test"];
/** Single first-party files outside those directories. */
const FILES = [
  "grammars/build.mjs",
  "web/vite.config.ts",
  "web/index.html",
  "pymtheg",
];
/** Never first-party source, wherever they appear. */
const SKIP_DIRS = new Set(["node_modules", "dist", "dist-web", ".git"]);
/** Excluded from tagging, one reason each. `untagged: true` also asserts the
 * tag is absent: tagging them would be wrong, not merely unneeded. */
const EXCLUDED = [
  {
    path: "web/src/generated/",
    untagged: true,
    why: "generated by scripts/schema.mjs",
  },
  {
    path: "test/fixtures/",
    untagged: true,
    why: "fixtures and sample projects that tests parse, index or copy as input; a tag would change the input",
  },
  {
    path: "grammars/go/",
    untagged: true,
    why: "vendored third-party grammar (tree-sitter-go) and its patches",
  },
  {
    path: "grammars/rust/",
    untagged: true,
    why: "vendored third-party grammar (tree-sitter-rust) and its patches",
  },
  {
    path: "examples/",
    untagged: false,
    why: "example and scaffold material users copy; out of LIC-2's scope",
  },
];
/** Our tag, in any of the comment styles scripts/spdx-tags.mjs writes, on any
 * line; an optional leading `+`, `-` or space also catches it inside a patch. */
const OURS =
  /^[+\- ]?[ \t]*(?:\/\/|\/\*|<!--|#)[ \t]*SPDX-License-Identifier: MIT\b/m;
/** Files under an `untagged: true` exclusion that may contain that line, one
 * reason each. Empty: no generated, fixture or vendored file contains any
 * `SPDX` text today. */
const ALLOWED = [];

/** Where the tag must sit: the line after a shebang or doctype, else line 1. */
function lineFor(path, text) {
  const line =
    LINE[extname(path)] ?? (text.startsWith("#!") ? `# ${TAG}` : undefined);
  if (!line) return undefined;
  let rest = text;
  if (rest.startsWith("#!")) rest = rest.slice(rest.indexOf("\n") + 1);
  else if (extname(path) === ".html")
    rest = rest.replace(/^<!doctype html>\n/i, "");
  return { line, rest };
}

function walk(root, dir, out) {
  let entries;
  try {
    entries = readdirSync(join(root, dir), { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const rel = dir ? `${dir}/${e.name}` : e.name;
    if (e.isDirectory()) {
      if (!SKIP_DIRS.has(e.name)) walk(root, rel, out);
    } else if (e.isFile()) out.push(rel);
  }
}

const excludedBy = (path) => EXCLUDED.find((x) => path.startsWith(x.path));

/** Returns { missing, misplaced } for the tree at `root`. */
function audit(root) {
  const inScope = new Set(FILES);
  for (const dir of ROOTS) {
    const files = [];
    walk(root, dir, files);
    for (const f of files) if (!excludedBy(f)) inScope.add(f);
  }
  for (const e of readdirSync(root, { withFileTypes: true }))
    if (e.isFile() && LINE[extname(e.name)]) inScope.add(e.name);

  const missing = [];
  let checked = 0;
  for (const path of [...inScope].sort()) {
    let text;
    try {
      text = readFileSync(join(root, path), "utf8");
    } catch {
      continue;
    }
    const at = lineFor(path, text);
    if (!at) continue;
    checked++;
    if (!at.rest.startsWith(`${at.line}\n`)) missing.push(path);
  }

  const misplaced = [];
  for (const x of EXCLUDED.filter((e) => e.untagged)) {
    const files = [];
    walk(root, x.path.replace(/\/$/, ""), files);
    for (const f of files) {
      if (ALLOWED.some((a) => a.path === f)) continue;
      const text = readFileSync(join(root, f), "utf8");
      if (OURS.test(text)) misplaced.push(`${f} (${x.why})`);
    }
  }
  return { missing, misplaced, checked };
}

test("every first-party source file carries the SPDX tag; excluded files do not", () => {
  const { missing, misplaced, checked } = audit(repo);
  assert.ok(
    checked > 700,
    `only ${checked} files found in scope: the walk is broken`,
  );
  assert.deepEqual(missing, [], "untagged: run node scripts/spdx-tags.mjs");
  assert.deepEqual(
    misplaced,
    [],
    "these excluded files must not carry Pymtheg's tag",
  );
});

test("the audit catches a missing tag and a tagged excluded file", () => {
  const root = mkdtempSync(join(tmpdir(), "pym-lic-tags-"));
  try {
    const put = (p, text) => {
      mkdirSync(join(root, p, ".."), { recursive: true });
      writeFileSync(join(root, p), text);
    };
    put("src/good.ts", `// ${TAG}\nexport {};\n`);
    put("src/bad.ts", "export {};\n");
    put("src/tag-not-first.ts", `export {};\n// ${TAG}\n`);
    put("scripts/run.mjs", `#!/usr/bin/env node\n// ${TAG}\n`);
    put("scripts/tool", "#!/bin/sh\necho\n");
    put("web/index.html", `<!doctype html>\n<!-- ${TAG} -->\n<html></html>\n`);
    put("web/src/a.css", `/* ${TAG} */\n`);
    put("web/src/generated/report.js", "export {};\n");
    put("pymtheg", `#!/bin/sh\n# ${TAG}\n`);
    put("grammars/build.mjs", `// ${TAG}\n`);
    put("web/vite.config.ts", `// ${TAG}\n`);
    put("test/fixtures/sample/main.ts", `// ${TAG}\nexport {};\n`);
    put("test/fixtures/sample/second.ts", `// Fixture input\n// ${TAG}\n`);
    put("test/fixtures/sample/style.css", `a {}\n/* ${TAG} */\n`);
    put("test/fixtures/sample/clean.ts", "export {};\n");
    put("web/src/generated/late.js", `export {};\n\n// ${TAG}\n`);
    put(
      "grammars/go/patches/0001.patch",
      `--- a/x.js\n+++ b/x.js\n+// ${TAG}\n`,
    );
    put("grammars/go/patches/0002.patch", "diff\n");
    put(
      "grammars/rust/src/upstream.c",
      "// SPDX-License-Identifier: Apache-2.0\n",
    );
    put("node_modules/x/index.js", "untagged third party\n");
    put("src/dist/out.js", "build output\n");
    const { missing, misplaced } = audit(root);
    assert.deepEqual(missing, [
      "scripts/tool",
      "src/bad.ts",
      "src/tag-not-first.ts",
    ]);
    assert.deepEqual(misplaced.map((m) => m.split(" ")[0]).sort(), [
      "grammars/go/patches/0001.patch",
      "test/fixtures/sample/main.ts",
      "test/fixtures/sample/second.ts",
      "test/fixtures/sample/style.css",
      "web/src/generated/late.js",
    ]);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
